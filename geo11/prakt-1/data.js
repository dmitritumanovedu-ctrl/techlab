export function parseNum(s) {
  const t = String(s ?? "").replace(/\s/g, "").replace(/[−–—]/g, "-").replace(",", ".").replace(/[^\d.\-]/g, "");
  const n = parseFloat(t);
  return Number.isFinite(n) ? n : null;
}
export function calcOk(k, val, key) {
  const x = parseNum(val);
  if (x === null) return false;
  if (k.startsWith("de_")) return Math.abs(x - key) <= Math.max(0.2, Math.abs(key) * 0.02);
  if (k.endsWith("x")) return Math.abs(x - key) <= 0.06;
  return Math.abs(x - key) <= 0.15;
}
